import React, { useEffect, useMemo, useState } from 'react'

// "📢 Push CAP SMS Alert" — drafts a Common Alerting Protocol (CAP 1.2, OASIS) heat alert, the
// format India's SACHET / NDMA alert system ingests. No CAP or SMS gateway is connected, so the
// alert is NOT transmitted: it is shown, copied or downloaded with status "Exercise", and the
// dialog says so. Content comes from the selected area's live reading and activation rules.
const esc = s => String(s ?? '').replace(/[<>&'"]/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' }[c]))
const SEV = { critical: ['Extreme', 'Immediate', 'Likely'], alert: ['Severe', 'Expected', 'Likely'], watch: ['Moderate', 'Future', 'Possible'], cold: ['Moderate', 'Expected', 'Likely'], routine: ['Minor', 'Future', 'Possible'] }

export function buildCapXml({ city, state, level = 'routine', tempNow, tempMax, reasons = [], sender = 'bhaskarops' }) {
  const now = new Date()
  const sent = new Date(now.getTime() + 5.5 * 3600e3).toISOString().replace(/\.\d+Z$/, '+05:30')
  const expires = new Date(now.getTime() + 5.5 * 3600e3 + 24 * 3600e3).toISOString().replace(/\.\d+Z$/, '+05:30')
  const [severity, urgency, certainty] = SEV[level] || SEV.routine
  const cold = level === 'cold'
  const area = [city, state, 'India'].filter(Boolean).join(', ') || 'India'
  const event = cold ? 'Cold Wave' : 'Heat Wave'
  const headline = cold ? `Cold-wave advisory for ${area}` : `${severity} heat advisory for ${area}`
  const desc = `${cold ? 'Low' : 'High'} temperatures${typeof tempMax === 'number' ? `: forecast maximum ${tempMax} °C` : ''}${typeof tempNow === 'number' ? `, now ${tempNow} °C` : ''}. ${reasons.join('; ')}`.trim()
  const instr = cold
    ? 'Wear layered warm clothing, keep the elderly and children warm, avoid unventilated indoor heaters, use night shelters.'
    : 'Avoid going out between 12:00 and 16:00. Drink water often even if not thirsty; use ORS. Check on elderly neighbours. Heat stroke is an emergency — call 108.'
  return `<?xml version="1.0" encoding="UTF-8"?>
<alert xmlns="urn:oasis:names:tc:emergency:cap:1.2">
  <identifier>${esc(sender)}-${now.getTime()}</identifier>
  <sender>${esc(sender)}@bhaskarops.gov.in</sender>
  <sent>${sent}</sent>
  <status>Exercise</status>
  <msgType>Alert</msgType>
  <scope>Public</scope>
  <note>DRAFT generated by BhaskarOps for review. Not transmitted: no CAP / SMS gateway is connected.</note>
  <info>
    <language>en-IN</language>
    <category>Met</category>
    <event>${event}</event>
    <urgency>${urgency}</urgency>
    <severity>${severity}</severity>
    <certainty>${certainty}</certainty>
    <expires>${expires}</expires>
    <senderName>BhaskarOps Heat Command</senderName>
    <headline>${esc(headline)}</headline>
    <description>${esc(desc)}</description>
    <instruction>${esc(instr)}</instruction>
    <area><areaDesc>${esc(area)}</areaDesc></area>
  </info>
</alert>`
}

export default function CapAlertButton({ city, state, level, tempNow, tempMax, reasons, className, style }) {
  const [open, setOpen] = useState(false)
  const [copied, setCopied] = useState(false)
  const xml = useMemo(() => (open ? buildCapXml({ city, state, level, tempNow, tempMax, reasons }) : ''), [open, city, state, level, tempNow, tempMax, reasons])
  useEffect(() => { if (!open) return; const k = e => { if (e.key === 'Escape') setOpen(false) }; window.addEventListener('keydown', k); return () => window.removeEventListener('keydown', k) }, [open])
  const sms = `${level === 'cold' ? 'COLD' : 'HEAT'} ALERT ${[city, state].filter(Boolean).join(', ') || 'India'}${typeof tempMax === 'number' ? `: max ${tempMax}°C` : ''}. ${level === 'cold' ? 'Stay warm; use night shelters.' : 'Avoid 12-4 PM outdoors, drink water, check on elderly. Emergency 108.'} -BhaskarOps (DRAFT)`
  const download = () => { const b = new Blob([xml], { type: 'application/xml' }); const u = URL.createObjectURL(b); const a = document.createElement('a'); a.href = u; a.download = `cap-alert-${(city || state || 'india').replace(/\W+/g, '-')}.xml`; document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(u), 1000) }
  return (
    <>
      <button type="button" onClick={() => setOpen(true)} data-testid="cap-alert" className={className} style={style} title="Draft a CAP 1.2 alert (SACHET format) for review">📢 Push CAP SMS Alert</button>
      {open && (
        <div role="dialog" aria-modal="true" aria-label="CAP alert draft" onClick={e => { if (e.target === e.currentTarget) setOpen(false) }} style={{ position: 'fixed', inset: 0, zIndex: 9000, background: 'rgba(2,6,23,0.7)', display: 'grid', placeItems: 'center', padding: 16 }}>
          <div style={{ width: 'min(720px, 100%)', maxHeight: '90vh', overflowY: 'auto', background: '#0B1325', border: '1px solid #1F2937', borderRadius: 12, padding: 16, color: '#E6EDF7', fontSize: 12 }}>
            <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
              <b style={{ fontSize: 15 }}>📢 CAP alert draft · {[city, state].filter(Boolean).join(', ') || 'All-India'}</b>
              <button type="button" onClick={() => setOpen(false)} aria-label="Close" style={{ marginLeft: 'auto', background: 'none', border: '1px solid #1F2937', color: '#93A4B8', borderRadius: 6, cursor: 'pointer', padding: '2px 8px' }}>✕</button>
            </div>
            <div style={{ margin: '8px 0', padding: '6px 9px', borderRadius: 7, background: 'rgba(245,158,11,0.1)', border: '1px solid rgba(245,158,11,0.45)', color: '#FCD34D' }}>
              Not transmitted. No SACHET / CAP or SMS gateway is connected, so this is a draft with status <b>Exercise</b> for the officer to review and forward through the authorised channel.
            </div>
            <div style={{ fontSize: 10, color: '#93A4B8', letterSpacing: '0.1em', fontWeight: 700 }}>SMS TEXT ({sms.length} characters)</div>
            <div style={{ background: '#111827', borderRadius: 7, padding: '7px 9px', margin: '4px 0 10px' }} data-testid="cap-sms">{sms}</div>
            <div style={{ fontSize: 10, color: '#93A4B8', letterSpacing: '0.1em', fontWeight: 700 }}>CAP 1.2 XML</div>
            <pre style={{ background: '#060B14', border: '1px solid #1F2937', borderRadius: 7, padding: 9, fontSize: 10.5, overflowX: 'auto', whiteSpace: 'pre-wrap' }} data-testid="cap-xml">{xml}</pre>
            <div style={{ display: 'flex', gap: 8 }}>
              <button type="button" onClick={() => { navigator.clipboard?.writeText(xml).then(() => { setCopied(true); setTimeout(() => setCopied(false), 1500) }).catch(() => {}) }} style={{ background: '#38BDF8', color: '#0f172a', border: 'none', borderRadius: 7, padding: '6px 12px', fontWeight: 800, cursor: 'pointer' }}>{copied ? 'Copied ✓' : 'Copy XML'}</button>
              <button type="button" onClick={download} style={{ background: '#F59E0B', color: '#0f172a', border: 'none', borderRadius: 7, padding: '6px 12px', fontWeight: 800, cursor: 'pointer' }}>Download .xml</button>
            </div>
          </div>
        </div>
      )}
    </>
  )
}
